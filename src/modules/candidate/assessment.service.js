const assessmentModel = require('./assessment.model');
const candidateModel = require('./candidate.model');
const assessmentMediaModel = require('./assessment-media.model');
const s3Service = require('./s3.service');
const auditModel = require('../auth/audit.model');
const eventBus = require('../../events/eventBus');

/**
 * Write an audit log without allowing audit-storage failures to
 * change the result of an already-completed business operation.
 */
const createAuditLogSafely = async (entry) => {
    try {
        await auditModel.createAuditLog(entry);
    } catch (error) {
        console.error(
            '[AUDIT] Failed to write assessment audit log:',
            error.message
        );
    }
};

/**
 * Validate that the current user is an authenticated Trade Tester.
 */
const validateTester = (user) => {
    if (!user) {
        const error = new Error('Authentication required');
        error.statusCode = 401;
        throw error;
    }

    if (user.role !== 'TRADE_TESTER') {
        const error = new Error(
            'Only Trade Testers can manage assessments'
        );
        error.statusCode = 403;
        throw error;
    }
};

/**
 * Validate score and grade.
 */
const validateAssessmentInput = ({ score, grade }) => {
    if (
        score === undefined ||
        score === null ||
        grade === undefined ||
        !grade
    ) {
        const error = new Error('Score and grade are required');
        error.statusCode = 400;
        throw error;
    }
};

/**
 * Create a DRAFT assessment.
 *
 * clientRequestId is generated by the frontend. It makes assessment
 * creation replay-safe when an offline request is synchronized again.
 */
const createAssessment = async ({
    candidateId,
    score,
    grade,
    clientRequestId,
    user
}) => {
    validateTester(user);
    validateAssessmentInput({ score, grade });

    if (!clientRequestId) {
        const error = new Error('clientRequestId is required');
        error.statusCode = 400;
        throw error;
    }

    const existingAssessment =
        await assessmentModel.findByClientRequestId({
            testerUserId: user.userId,
            clientRequestId
        });

    if (existingAssessment) {
        return {
            assessment: existingAssessment,
            replayed: true
        };
    }

    const candidate = await candidateModel.findById(candidateId);

    if (!candidate) {
        const error = new Error('Candidate not found');
        error.statusCode = 404;
        throw error;
    }

    if (candidate.testing_hub_id !== user.hubLocationId) {
        const error = new Error(
            'Candidate does not belong to your testing hub'
        );
        error.statusCode = 403;
        throw error;
    }

    try {
        const assessment = await assessmentModel.createAssessment({
            candidateId,
            score,
            grade,
            testerUserId: user.userId,
            clientRequestId
        });

        return {
            assessment,
            replayed: false
        };
    } catch (error) {
        // PostgreSQL unique_violation: check whether this request
        // was processed concurrently.
        if (error.code === '23505') {
            const replayedAssessment =
                await assessmentModel.findByClientRequestId({
                    testerUserId: user.userId,
                    clientRequestId
                });

            if (replayedAssessment) {
                return {
                    assessment: replayedAssessment,
                    replayed: true
                };
            }
        }

        throw error;
    }
};

/**
 * Get one assessment.
 */
const getAssessment = async ({ assessmentId, user }) => {
    validateTester(user);

    const assessment = await assessmentModel.findById(assessmentId);

    if (!assessment) {
        const error = new Error('Assessment not found');
        error.statusCode = 404;
        throw error;
    }

    // The owner can access directly. Another Trade Tester from the
    // same hub may also view the assessment.
    if (assessment.tester_user_id !== user.userId) {
        const candidate = await candidateModel.findById(
            assessment.candidate_id
        );

        if (!candidate) {
            const error = new Error('Candidate not found');
            error.statusCode = 404;
            throw error;
        }

        if (candidate.testing_hub_id !== user.hubLocationId) {
            const error = new Error('Access denied');
            error.statusCode = 403;
            throw error;
        }
    }

    return assessment;
};

/**
 * Update the score and grade of an existing DRAFT assessment.
 */
const updateAssessment = async ({
    assessmentId,
    score,
    grade,
    user
}) => {
    validateTester(user);
    validateAssessmentInput({ score, grade });

    const assessment = await assessmentModel.findById(assessmentId);

    if (!assessment) {
        const error = new Error('Assessment not found');
        error.statusCode = 404;
        throw error;
    }

    if (assessment.tester_user_id !== user.userId) {
        const error = new Error(
            'You can only update your own assessments'
        );
        error.statusCode = 403;
        throw error;
    }

    if (assessment.status !== 'DRAFT') {
        const error = new Error(
            'Only DRAFT assessments can be updated'
        );
        error.statusCode = 409;
        throw error;
    }

    const updatedAssessment = await assessmentModel.updateDraft({
        assessmentId,
        score,
        grade,
        testerUserId: user.userId
    });

    if (!updatedAssessment) {
        const error = new Error(
            'Assessment could not be updated'
        );
        error.statusCode = 409;
        throw error;
    }

    return updatedAssessment;
};

/**
 * Generate a pre-signed S3 URL for the required evidence photo.
 */
const createAssessmentPhotoUploadUrl = async ({
    assessmentId,
    contentType,
    user
}) => {
    validateTester(user);

    const assessment = await assessmentModel.findById(assessmentId);

    if (!assessment) {
        const error = new Error('Assessment not found');
        error.statusCode = 404;
        throw error;
    }

    if (assessment.tester_user_id !== user.userId) {
        const error = new Error(
            'You can only manage your own assessments'
        );
        error.statusCode = 403;
        throw error;
    }

    if (assessment.status !== 'DRAFT') {
        const error = new Error(
            'Photo can only be uploaded for DRAFT assessments'
        );
        error.statusCode = 409;
        throw error;
    }

    // MVP supports exactly one evidence photo.
    const existingMedia =
        await assessmentMediaModel.findOneByAssessment(assessmentId);

    if (existingMedia) {
        const error = new Error(
            'Assessment already has an evidence photo'
        );
        error.statusCode = 409;
        throw error;
    }

    return s3Service.createAssessmentPhotoUploadUrl({
        assessmentId,
        userId: user.userId,
        contentType
    });
};

/**
 * Save metadata for the uploaded evidence photo.
 * The image itself is stored in S3; PostgreSQL stores its S3 URI.
 */
const addAssessmentMedia = async ({
    assessmentId,
    mediaS3Uri,
    user
}) => {
    validateTester(user);

    if (!mediaS3Uri) {
        const error = new Error(
            'Assessment photo S3 URI is required'
        );
        error.statusCode = 400;
        throw error;
    }

    const assessment = await assessmentModel.findById(assessmentId);

    if (!assessment) {
        const error = new Error('Assessment not found');
        error.statusCode = 404;
        throw error;
    }

    if (assessment.tester_user_id !== user.userId) {
        const error = new Error(
            'You can only add media to your own assessments'
        );
        error.statusCode = 403;
        throw error;
    }

    if (assessment.status !== 'DRAFT') {
        const error = new Error(
            'Media can only be added to DRAFT assessments'
        );
        error.statusCode = 409;
        throw error;
    }

    // MVP rule: one evidence photo only.
    const existingMedia =
        await assessmentMediaModel.findOneByAssessment(assessmentId);

    if (existingMedia) {
        const error = new Error(
            'Assessment already has an evidence photo'
        );
        error.statusCode = 409;
        throw error;
    }

    return assessmentMediaModel.createMedia({
        assessmentId,
        mediaType: 'IMAGE',
        mediaS3Uri
    });
};

