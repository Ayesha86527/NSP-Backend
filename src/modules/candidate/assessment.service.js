/*
 * Validate that the current user is an authenticated Trade Tester.
 */
const validateTester = (user) => {
    if (!user) {
        const error = new Error('Authentication required');
        error.statusCode = 401;
        throw error;
    }

    if (user.role !== 'TRADE_TESTER') {
        const error = new Error(
            'Only Trade Testers can manage assessments'
        );
        error.statusCode = 403;
        throw error;
    }
};


/*
 * Validate score and grade.
 */
const validateAssessmentInput = ({
    score,
    grade
}) => {
    if (
        score === undefined ||
        score === null ||
        grade === undefined ||
        !grade
    ) {
        const error = new Error(
            'Score and grade are required'
        );
        error.statusCode = 400;
        throw error;
    }
};


/*
 * Create a DRAFT assessment.
 *
 * clientRequestId is generated by the frontend.
 * It makes assessment creation replay-safe when an offline
 * request is synchronized more than once.
 */
const createAssessment = async ({
    candidateId,
    score,
    grade,
    clientRequestId,
    user
}) => {
    validateTester(user);

    validateAssessmentInput({
        score,
        grade
    });

    if (!clientRequestId) {
        const error = new Error(
            'clientRequestId is required'
        );
        error.statusCode = 400;
        throw error;
    }

    /*
     * Check whether this offline/client request was already
     * processed.
     */
    const existingAssessment =
        await assessmentModel.findByClientRequestId({
            testerUserId: user.userId,
            clientRequestId
        });

    if (existingAssessment) {
        return {
            assessment: existingAssessment,
            replayed: true
        };
    }

    /*
     * Candidate must exist.
     */
    const candidate = await candidateModel.findById(
        candidateId
    );

    if (!candidate) {
        const error = new Error(
            'Candidate not found'
        );
        error.statusCode = 404;
        throw error;
    }

    /*
     * Trade Tester can only assess candidates belonging
     * to their testing hub.
     */
    if (
        candidate.testing_hub_id !==
        user.hubLocationId
    ) {
        const error = new Error(
            'Candidate does not belong to your testing hub'
        );
        error.statusCode = 403;
        throw error;
    }

    /*
     * Database UNIQUE protection handles the small race
     * condition where the same clientRequestId arrives
     * simultaneously.
     */
    try {
        const assessment =
            await assessmentModel.createAssessment({
                candidateId,
                score,
                grade,
                testerUserId: user.userId,
                clientRequestId
            });

        return {
            assessment,
            replayed: false
        };
    } catch (error) {
        /*
         * PostgreSQL unique_violation.
         */
        if (error.code === '23505') {
            const replayedAssessment =
                await assessmentModel
                    .findByClientRequestId({
                        testerUserId: user.userId,
                        clientRequestId
                    });

            if (replayedAssessment) {
                return {
                    assessment: replayedAssessment,
                    replayed: true
                };
            }
        }

        throw error;
    }
};


/*
 * Get one assessment.
 */
const getAssessment = async ({
    assessmentId,
    user
}) => {
    validateTester(user);

    const assessment =
        await assessmentModel.findById(
            assessmentId
        );

    if (!assessment) {
        const error = new Error(
            'Assessment not found'
        );
        error.statusCode = 404;
        throw error;
    }

    /*
     * Owner can access directly.
     *
     * Existing behavior also permits another Trade Tester
     * from the same hub to view the assessment.
     */
    if (
        assessment.tester_user_id !==
        user.userId
    ) {
        const candidate =
            await candidateModel.findById(
                assessment.candidate_id
            );

        if (!candidate) {
            const error = new Error(
                'Candidate not found'
            );
            error.statusCode = 404;
            throw error;
        }

        if (
            candidate.testing_hub_id !==
            user.hubLocationId
        ) {
            const error = new Error(
                'Access denied'
            );
            error.statusCode = 403;
            throw error;
        }
    }

    return assessment;
};


/*
 * Update score/grade of an existing DRAFT.
 */
const updateAssessment = async ({
    assessmentId,
    score,
    grade,
    user
}) => {
    validateTester(user);

    validateAssessmentInput({
        score,
        grade
    });

    const assessment =
        await assessmentModel.findById(
            assessmentId
        );

    if (!assessment) {
        const error = new Error(
            'Assessment not found'
        );
        error.statusCode = 404;
        throw error;
    }

    if (
        assessment.tester_user_id !==
        user.userId
    ) {
        const error = new Error(
            'You can only update your own assessments'
        );
        error.statusCode = 403;
        throw error;
    }

    if (assessment.status !== 'DRAFT') {
        const error = new Error(
            'Only DRAFT assessments can be updated'
        );
        error.statusCode = 409;
        throw error;
    }

    const updatedAssessment =
        await assessmentModel.updateDraft({
            assessmentId,
            score,
            grade,
            testerUserId: user.userId
        });

    if (!updatedAssessment) {
        const error = new Error(
            'Assessment could not be updated'
        );
        error.statusCode = 409;
        throw error;
    }

    return updatedAssessment;
};


/*
 * Generate a pre-signed S3 URL for the single required
 * assessment evidence photo.
 *
 * Actual S3/IAM testing will be done in the EC2 deployment.
 */
const createAssessmentPhotoUploadUrl = async ({
    assessmentId,
    user
}) => {
    validateTester(user);

    const assessment =
        await assessmentModel.findById(
            assessmentId
        );

    if (!assessment) {
        const error = new Error(
            'Assessment not found'
        );
        error.statusCode = 404;
        throw error;
    }

    if (
        assessment.tester_user_id !==
        user.userId
    ) {
        const error = new Error(
            'You can only manage your own assessments'
        );
        error.statusCode = 403;
        throw error;
    }

    if (assessment.status !== 'DRAFT') {
        const error = new Error(
            'Photo can only be uploaded for DRAFT assessments'
        );
        error.statusCode = 409;
        throw error;
    }

    /*
     * MVP supports exactly one evidence photo.
     */
    const existingMedia =
        await assessmentMediaModel
            .findOneByAssessment(
                assessmentId
            );

    if (existingMedia) {
        const error = new Error(
            'Assessment already has an evidence photo'
        );
        error.statusCode = 409;
        throw error;
    }

    return s3Service
        .createAssessmentPhotoUploadUrl({
            assessmentId,
            userId: user.userId
        });
};


