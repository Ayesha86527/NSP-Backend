/**
 * Write an audit log without allowing audit-storage failures to
 * change the result of an already-completed business operation.
 */
const createAuditLogSafely = async (entry) => {
    try {
        await auditModel.createAuditLog(entry);
    } catch (error) {
        console.error(
            '[AUDIT] Failed to write assessment audit log:',
            error.message
        );
    }
};

/**
 * Validate that the current user may create and manage assessments:
 * a Trade Tester, a Center Superintendent or a Super Admin.
 *
 * Trade Testers and Superintendents must belong to a hub.
 * Super Admins are not tied to a hub.
 */
const ASSESSOR_ROLES = [
    'TRADE_TESTER',
    'CENTER_SUPERINTENDENT',
    'SUPERINTENDENT',
    'SUPER_ADMIN'
];

const validateTester = (user) => {
    if (!user) {
        const error = new Error('Authentication required');
        error.statusCode = 401;
        throw error;
    }

    if (!ASSESSOR_ROLES.includes(user.role)) {
        const error = new Error(
            'Only Trade Testers, Superintendents and Super Admins can manage assessments'
        );
        error.statusCode = 403;
        throw error;
    }

    if (
        user.role !== 'SUPER_ADMIN' &&
        (user.hubLocationId === undefined || user.hubLocationId === null)
    ) {
        const error = new Error('A testing hub is required');
        error.statusCode = 403;
        throw error;
    }
};

/**
 * Hub scope: Super Admins reach every hub, everyone else only their own.
 */
const isInUserScope = (user, candidate) =>
    user.role === 'SUPER_ADMIN' ||
    candidate.testing_hub_id === user.hubLocationId;

/**
 * Score/grade rules. The database column is NUMERIC(5,2) and
 * VARCHAR(10); anything outside that used to crash with a raw
 * database error (HTTP 500). Reject it with a clear 400 instead.
 */
const MIN_SCORE = 0;
const MAX_SCORE = 100; // change here if your marking scale is different
const MAX_GRADE_LENGTH = 10;

const badRequest = (message) => {
    const error = new Error(message);
    error.statusCode = 400;
    return error;
};

/**
 * PostgreSQL rejects malformed input (22P02 invalid text/uuid/number,
 * 22003 numeric overflow, 22001 value too long). Report those as a
 * client error instead of an HTTP 500.
 */
const asClientError = (error) => {
    if (error && ['22P02', '22003', '22001'].includes(error.code)) {
        return badRequest(
            'Invalid input: clientRequestId must be a valid UUID and ' +
            'score/grade must fit the allowed format'
        );
    }

    return error;
};

const isBlank = (value) =>
    value === undefined ||
    value === null ||
    (typeof value === 'string' && value.trim() === '');

const normalizeScore = (score) => {
    const value = typeof score === 'string' ? Number(score.trim()) : score;

    if (
        typeof value !== 'number' ||
        !Number.isFinite(value) ||
        value < MIN_SCORE ||
        value > MAX_SCORE
    ) {
        throw badRequest(
            `Score must be a number between ${MIN_SCORE} and ${MAX_SCORE}`
        );
    }

    // The column keeps two decimal places.
    return Math.round(value * 100) / 100;
};

const normalizeGrade = (grade) => {
    if (typeof grade !== 'string' || !grade.trim()) {
        throw badRequest('Grade must be a non-empty text value');
    }

    const value = grade.trim();

    if (value.length > MAX_GRADE_LENGTH) {
        throw badRequest(
            `Grade must be at most ${MAX_GRADE_LENGTH} characters`
        );
    }

    return value;
};

/**
 * Validate and normalise score and grade (both required).
 */
const validateAssessmentInput = ({ score, grade }) => {
    if (isBlank(score) || isBlank(grade)) {
        throw badRequest('Score and grade are required');
    }

    return {
        score: normalizeScore(score),
        grade: normalizeGrade(grade)
    };
};

/**
 * Validate a partial draft update: at least one of score/grade,
 * and whichever is supplied must be valid.
 */
const validatePartialAssessmentInput = ({ score, grade }) => {
    if (isBlank(score) && isBlank(grade)) {
        throw badRequest('Provide a score, a grade, or both');
    }

    return {
        score: isBlank(score) ? undefined : normalizeScore(score),
        grade: isBlank(grade) ? undefined : normalizeGrade(grade)
    };
};

/**
 * Create a DRAFT assessment.
 *
 * clientRequestId is generated by the frontend. It makes assessment
 * creation replay-safe when an offline request is synchronized again.
 */
const createAssessment = async ({
    candidateId,
    score,
    grade,
    clientRequestId,
    user
}) => {
    validateTester(user);

    const cleaned = validateAssessmentInput({ score, grade });
    score = cleaned.score;
    grade = cleaned.grade;

    if (!clientRequestId) {
        const error = new Error('clientRequestId is required');
        error.statusCode = 400;
        throw error;
    }

    let existingAssessment;

    try {
        existingAssessment =
            await assessmentModel.findByClientRequestId({
                testerUserId: user.userId,
                clientRequestId
            });
    } catch (error) {
        throw asClientError(error);
    }

    if (existingAssessment) {
        return {
            assessment: existingAssessment,
            replayed: true
        };
    }

    const candidate = await candidateModel.findById(candidateId);

    if (!candidate) {
        const error = new Error('Candidate not found');
        error.statusCode = 404;
        throw error;
    }

    if (!isInUserScope(user, candidate)) {
        const error = new Error(
            'Candidate does not belong to your testing hub'
        );
        error.statusCode = 403;
        throw error;
    }

    try {
        const assessment = await assessmentModel.createAssessment({
            candidateId,
            score,
            grade,
            testerUserId: user.userId,
            clientRequestId
        });

        return {
            assessment,
            replayed: false
        };
    } catch (error) {
        // PostgreSQL unique_violation: check whether this request
        // was processed concurrently.
        if (error.code === '23505') {
            const replayedAssessment =
                await assessmentModel.findByClientRequestId({
                    testerUserId: user.userId,
                    clientRequestId
                });

            if (replayedAssessment) {
                return {
                    assessment: replayedAssessment,
                    replayed: true
                };
            }
        }

        throw asClientError(error);
    }
};

/**
 * Get one assessment.
 */
const getAssessment = async ({ assessmentId, user }) => {
    validateTester(user);

    const assessment = await assessmentModel.findById(assessmentId);

    if (!assessment) {
        const error = new Error('Assessment not found');
        error.statusCode = 404;
        throw error;
    }

    // The owner can access directly. Another Trade Tester from the
    // same hub may also view the assessment.
    if (assessment.tester_user_id !== user.userId) {
        const candidate = await candidateModel.findById(
            assessment.candidate_id
        );

        if (!candidate) {
            const error = new Error('Candidate not found');
            error.statusCode = 404;
            throw error;
        }

        if (!isInUserScope(user, candidate)) {
            const error = new Error('Access denied');
            error.statusCode = 403;
            throw error;
        }
    }

    return assessment;
};

/**
 * Update the score and grade of an existing DRAFT assessment.
 */
const updateAssessment = async ({
    assessmentId,
    score,
    grade,
    user
}) => {
    validateTester(user);

    // Autosave-friendly: a draft can be updated with just a score,
    // just a grade, or both.
    const cleaned = validatePartialAssessmentInput({ score, grade });
    score = cleaned.score;
    grade = cleaned.grade;

    const assessment = await assessmentModel.findById(assessmentId);

    if (!assessment) {
        const error = new Error('Assessment not found');
        error.statusCode = 404;
        throw error;
    }

    if (assessment.tester_user_id !== user.userId) {
        const error = new Error(
            'You can only update your own assessments'
        );
        error.statusCode = 403;
        throw error;
    }

    if (assessment.status !== 'DRAFT') {
        const error = new Error(
            'Only DRAFT assessments can be updated'
        );
        error.statusCode = 409;
        throw error;
    }

    const updatedAssessment = await assessmentModel.updateDraft({
        assessmentId,
        score,
        grade,
        testerUserId: user.userId
    });

    if (!updatedAssessment) {
        const error = new Error(
            'Assessment could not be updated'
        );
        error.statusCode = 409;
        throw error;
    }

    return updatedAssessment;
};

/**
 * Generate a pre-signed S3 URL for the required evidence photo.
 */
const createAssessmentPhotoUploadUrl = async ({
    assessmentId,
    contentType,
    user
}) => {
    validateTester(user);

    const assessment = await assessmentModel.findById(assessmentId);

    if (!assessment) {
        const error = new Error('Assessment not found');
        error.statusCode = 404;
        throw error;
    }

    if (assessment.tester_user_id !== user.userId) {
        const error = new Error(
            'You can only manage your own assessments'
        );
        error.statusCode = 403;
        throw error;
    }

    if (assessment.status !== 'DRAFT') {
        const error = new Error(
            'Photo can only be uploaded for DRAFT assessments'
        );
        error.statusCode = 409;
        throw error;
    }

    // MVP supports exactly one evidence photo.
    const existingMedia =
        await assessmentMediaModel.findOneByAssessment(assessmentId);

    if (existingMedia) {
        const error = new Error(
            'Assessment already has an evidence photo'
        );
        error.statusCode = 409;
        throw error;
    }

    return s3Service.createAssessmentPhotoUploadUrl({
        assessmentId,
        userId: user.userId,
        contentType
    });
};

