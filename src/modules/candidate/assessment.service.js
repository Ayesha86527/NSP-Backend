/**
 * List assessments for the logged-in user (GET /api/assessments).
 *
 * - Trade Tester: only their own assessments.
 * - Center Superintendent: every assessment in their hub.
 * - Super Admin: every assessment in every hub.
 */
const getMyAssessments = async ({ user }) => {
    validateTester(user);

    if (user.role === 'SUPER_ADMIN') {
        return assessmentModel.findByHub(null);
    }

    if (user.role === 'TRADE_TESTER') {
        return assessmentModel.findByTester(user.userId);
    }

    return assessmentModel.findByHub(user.hubLocationId);
};

/**
 * Validate that the current user is an authenticated
 * Center Superintendent.
 */
const validateSuperintendent = (user) => {
    if (!user) {
        const error = new Error('Authentication required');
        error.statusCode = 401;
        throw error;
    }

    if (
        !['CENTER_SUPERINTENDENT', 'SUPERINTENDENT', 'SUPER_ADMIN'].includes(
            user.role
        )
    ) {
        const error = new Error(
            'Only Center Superintendents can approve or reject assessments'
        );
        error.statusCode = 403;
        throw error;
    }

    // Super Admins are not tied to a hub; superintendents must have one.
    if (
        user.role !== 'SUPER_ADMIN' &&
        (user.hubLocationId === undefined || user.hubLocationId === null)
    ) {
        const error = new Error('Superintendent hub is required');
        error.statusCode = 403;
        throw error;
    }
};

/**
 * Superintendents are limited to their own hub.
 * Super Admins are not hub-scoped.
 */
const assertCanActOnHub = (user, candidate) => {
    if (user.role === 'SUPER_ADMIN') {
        return;
    }

    if (candidate.testing_hub_id !== user.hubLocationId) {
        const error = new Error(
            'Assessment does not belong to your testing hub'
        );
        error.statusCode = 403;
        throw error;
    }
};

/**
 * Get SUBMITTED assessments for the Superintendent's hub
 * (all hubs for a Super Admin).
 */
const getApprovalQueue = async ({ user }) => {
    validateSuperintendent(user);

    // Super Admins see SUBMITTED assessments from every hub.
    return assessmentModel.findSubmittedForSuperintendent(
        user.role === 'SUPER_ADMIN' ? null : user.hubLocationId
    );
};

/**
 * Approve a SUBMITTED assessment.
 */
const approveAssessment = async ({ assessmentId, user }) => {
    validateSuperintendent(user);

    const assessment = await assessmentModel.findById(assessmentId);

    if (!assessment) {
        const error = new Error('Assessment not found');
        error.statusCode = 404;
        throw error;
    }

    if (assessment.status === 'MINTED') {
        const error = new Error(
            'MINTED assessments cannot be approved or rejected'
        );
        error.statusCode = 409;
        throw error;
    }

    // Verify that the candidate belongs to the Superintendent's hub.
    const candidate = await candidateModel.findById(
        assessment.candidate_id
    );

    if (!candidate) {
        const error = new Error('Candidate not found');
        error.statusCode = 404;
        throw error;
    }

    assertCanActOnHub(user, candidate);

    if (assessment.status !== 'SUBMITTED') {
        const error = new Error(
            'Only SUBMITTED assessments can be approved'
        );
        error.statusCode = 409;
        throw error;
    }

    const approvedAssessment =
        await assessmentModel.approveAssessment({
            assessmentId,
            superintendentUserId: user.userId
        });

    if (!approvedAssessment) {
        const error = new Error(
            'Assessment could not be approved'
        );
        error.statusCode = 409;
        throw error;
    }

    // The database approval has succeeded. Audit failure must not
    // cause the API to report that the approval itself failed.
    await createAuditLogSafely({
        userId: user.userId,
        eventType: 'ASSESSMENT_APPROVED',
        ipAddress: null,
        details: {
            assessmentId: approvedAssessment.assessment_id,
            candidateId: approvedAssessment.candidate_id,
            hubId: approvedAssessment.testing_hub_id,
            approverRole: user.role
        }
    });

    // Keep the shared event payload contract unchanged.
    const eventPayload = {
        assessmentId: approvedAssessment.assessment_id,
        candidateId: approvedAssessment.candidate_id,
        hubId: approvedAssessment.testing_hub_id,
        tradeCategory: approvedAssessment.trade_category,
        grade: approvedAssessment.grade,
        score: approvedAssessment.score,
        approvedAt: approvedAssessment.approved_at,
        superintendentUserId:
            approvedAssessment.superintendent_user_id
    };

    try {
        const emitted = eventBus.emitSafely(
            'assessment.approved',
            eventPayload
        );

        if (emitted) {
            console.log(
                '[EVENT] assessment.approved emitted',
                eventPayload.assessmentId
            );
        } else {
            console.error(
                '[EVENT] One or more assessment.approved listeners failed; ' +
                'assessment remains approved:',
                eventPayload.assessmentId
            );
        }
    } catch (error) {
        // Approval is already committed. Do not turn a successful
        // database operation into a failed HTTP response.
        console.error(
            '[EVENT] Failed to emit assessment.approved:',
            error.message
        );
    }

    return approvedAssessment;
};

/**
 * Reject a SUBMITTED assessment.
 *
 * SDD §6.2.3:
 * SUBMITTED → REJECTED → DRAFT
 *
 * The final database state is DRAFT so the Trade Tester can edit
 * and resubmit the assessment.
 */
const rejectAssessment = async ({
    assessmentId,
    rejectionReason,
    user
}) => {
    validateSuperintendent(user);

    if (
        typeof rejectionReason !== 'string' ||
        !rejectionReason.trim()
    ) {
        const error = new Error('Rejection reason is required');
        error.statusCode = 400;
        throw error;
    }

    const assessment = await assessmentModel.findById(assessmentId);

    if (!assessment) {
        const error = new Error('Assessment not found');
        error.statusCode = 404;
        throw error;
    }

    if (assessment.status === 'MINTED') {
        const error = new Error(
            'MINTED assessments cannot be approved or rejected'
        );
        error.statusCode = 409;
        throw error;
    }

    const candidate = await candidateModel.findById(
        assessment.candidate_id
    );

    if (!candidate) {
        const error = new Error('Candidate not found');
        error.statusCode = 404;
        throw error;
    }

    assertCanActOnHub(user, candidate);

    if (assessment.status !== 'SUBMITTED') {
        const error = new Error(
            'Only SUBMITTED assessments can be rejected'
        );
        error.statusCode = 409;
        throw error;
    }

    const rejectedAssessment =
        await assessmentModel.rejectAssessment({
            assessmentId,
            superintendentUserId: user.userId,
            rejectionReason: rejectionReason.trim()
        });

    if (!rejectedAssessment) {
        const error = new Error(
            'Assessment could not be rejected'
        );
        error.statusCode = 409;
        throw error;
    }

    // The rejection and return-to-draft transition have succeeded.
    // Audit storage errors must not invalidate that result.
    await createAuditLogSafely({
        userId: user.userId,
        eventType: 'ASSESSMENT_REJECTED',
        ipAddress: null,
        details: {
            assessmentId: rejectedAssessment.assessment_id,
            candidateId: rejectedAssessment.candidate_id,
            hubId: rejectedAssessment.testing_hub_id,
            rejectionReason: rejectedAssessment.rejection_reason
        }
    });

    await createAuditLogSafely({
        userId: user.userId,
        eventType: 'ASSESSMENT_RETURNED_TO_DRAFT',
        ipAddress: null,
        details: {
            assessmentId: rejectedAssessment.assessment_id,
            candidateId: rejectedAssessment.candidate_id,
            reason: 'SUPERINTENDENT_REJECTION'
        }
    });

    return rejectedAssessment;
};

