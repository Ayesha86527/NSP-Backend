/*
 * Submit a DRAFT assessment for Superintendent review.
 *
 * MVP requirement:
 * one evidence photo must exist before DRAFT can move
 * to SUBMITTED.
 */
const submitAssessment = async ({
    assessmentId,
    user
}) => {
    validateTester(user);

    const assessment =
        await assessmentModel.findById(
            assessmentId
        );

    if (!assessment) {
        const error = new Error(
            'Assessment not found'
        );
        error.statusCode = 404;
        throw error;
    }

    if (
        assessment.tester_user_id !==
        user.userId
    ) {
        const error = new Error(
            'You can only submit your own assessments'
        );
        error.statusCode = 403;
        throw error;
    }

    if (assessment.status !== 'DRAFT') {
        const error = new Error(
            'Only DRAFT assessments can be submitted'
        );
        error.statusCode = 409;
        throw error;
    }

    /*
     * Evidence photo is mandatory for submission.
     */
    const assessmentMedia =
        await assessmentMediaModel
            .findOneByAssessment(
                assessmentId
            );

    if (!assessmentMedia) {
        const error = new Error(
            'Assessment evidence photo is required before submission'
        );
        error.statusCode = 409;
        throw error;
    }

    const submittedAssessment =
        await assessmentModel.submitDraft({
            assessmentId,
            testerUserId: user.userId
        });

    if (!submittedAssessment) {
        const error = new Error(
            'Assessment could not be submitted'
        );
        error.statusCode = 409;
        throw error;
    }

    return submittedAssessment;
};


/*
 * Get assessments belonging to the logged-in Trade Tester.
 */
const getMyAssessments = async ({
    user
}) => {
    validateTester(user);

    return assessmentModel.findByTester(
        user.userId
    );
};


