const crypto = require('crypto');
const CandidateModel = require('../candidate/candidate.model');
const LedgerModel = require('./ledger.model');

const UUID_PATTERN = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
const CREDENTIAL_ID_PATTERN = /^urn:uuid:[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
const MAX_SUBJECT_BYTES = 16 * 1024;

const validationError = (message, statusCode = 400) => {
    const error = new Error(message);
    error.statusCode = statusCode;
    return error;
};

const stableStringify = (value) => {
    if (Array.isArray(value)) {
        return `[${value.map(stableStringify).join(',')}]`;
    }

    if (value && typeof value === 'object') {
        const entries = Object.keys(value)
            .sort()
            .map((key) => `${JSON.stringify(key)}:${stableStringify(value[key])}`);
        return `{${entries.join(',')}}`;
    }

    return JSON.stringify(value);
};

const validateCredentialInput = (body) => {
    if (!body || typeof body !== 'object' || Array.isArray(body)) {
        throw validationError('Request body must be a JSON object.');
    }

    const { candidateId, credentialSubject } = body;
    if (typeof candidateId !== 'string' || !UUID_PATTERN.test(candidateId)) {
        throw validationError('candidateId must be a valid UUID.');
    }

    if (
        !credentialSubject ||
        typeof credentialSubject !== 'object' ||
        Array.isArray(credentialSubject) ||
        Object.getPrototypeOf(credentialSubject) !== Object.prototype
    ) {
        throw validationError('credentialSubject must be a JSON object.');
    }

    if (Object.prototype.hasOwnProperty.call(credentialSubject, 'id')) {
        throw validationError('credentialSubject.id is generated by the server and must not be provided.');
    }

    for (const key of Object.keys(credentialSubject)) {
        if (['__proto__', 'constructor', 'prototype'].includes(key)) {
            throw validationError(`credentialSubject.${key} is not allowed.`);
        }
    }

    for (const field of ['skillName', 'issuer']) {
        const value = credentialSubject[field];
        if (typeof value !== 'string' || value.trim().length === 0) {
            throw validationError(`credentialSubject.${field} must be a non-empty string.`);
        }
        if (value.length > 500) {
            throw validationError(`credentialSubject.${field} must be 500 characters or fewer.`);
        }
    }

    let subjectSize;
    try {
        subjectSize = Buffer.byteLength(JSON.stringify(credentialSubject), 'utf8');
    } catch {
        throw validationError('credentialSubject must contain only JSON-compatible values.');
    }

    if (subjectSize > MAX_SUBJECT_BYTES) {
        throw validationError('credentialSubject must be 16 KB or smaller.');
    }

    return {
        candidateId,
        credentialSubject: {
            ...credentialSubject,
            skillName: credentialSubject.skillName.trim(),
            issuer: credentialSubject.issuer.trim()
        }
    };
};

const validateCredentialId = (credentialId) => {
    if (
        typeof credentialId !== 'string' ||
        !CREDENTIAL_ID_PATTERN.test(credentialId)
    ) {
        throw validationError('credentialId must be a valid urn:uuid credential ID.');
    }
};

const issueCredentialOnly = async (reqBody, user) => {
    const { candidateId, credentialSubject } = validateCredentialInput(reqBody);
    if (user.hubLocationId === undefined || user.hubLocationId === null) {
        throw validationError('Trade Tester hub is required.', 403);
    }

    const candidate = await CandidateModel.findByIdInHub(
        candidateId,
        user.hubLocationId
    );

    if (!candidate) {
        throw validationError('Candidate not found.', 404);
    }

    const credentialId = `urn:uuid:${crypto.randomUUID()}`;
    const w3cCredential = {
        '@context': [
            'https://www.w3.org/2018/credentials/v1',
            'https://schema.nsp.gov.pk/contexts/v1.json'
        ],
        id: credentialId,
        type: ['VerifiableCredential', 'NationalSkillsCredential'],
        issuer: credentialSubject.issuer,
        issuanceDate: new Date().toISOString(),
        credentialSubject: {
            ...credentialSubject,
            id: `did:nsp:candidate:${candidateId}`
        }
    };

    const rootHash = `0x${crypto
        .createHash('sha256')
        .update(stableStringify(w3cCredential))
        .digest('hex')}`;

    return LedgerModel.createCredential({
        credentialId,
        candidateId,
        createdBy: user.userId,
        credentialSubject: w3cCredential,
        rootHash
    });
};

const approveAndQueueCredential = async (credentialId, approver) => {
    validateCredentialId(credentialId);
    if (!['CENTER_SUPERINTENDENT', 'SUPER_ADMIN'].includes(approver.role)) {
        throw validationError('Only Center Superintendents or Super Admins can approve credentials.', 403);
    }
    if (
        approver.role === 'CENTER_SUPERINTENDENT' &&
        (approver.hubLocationId === undefined || approver.hubLocationId === null)
    ) {
        throw validationError('Superintendent hub is required.', 403);
    }

    return LedgerModel.approveAndQueueCredential({
        credentialId,
        approverId: approver.userId,
        approverRole: approver.role,
        hubLocationId: approver.hubLocationId
    });
};

const getCredentialStatus = async (credentialId, user) => {
    validateCredentialId(credentialId);
    const result = await LedgerModel.getCredentialStatus(credentialId, user);
    if (!result) {
        throw validationError('Credential not found.', 404);
    }
    return result;
};

module.exports = {
    issueCredentialOnly,
    approveAndQueueCredential,
    getCredentialStatus,
    validateCredentialInput,
    validateCredentialId,
    stableStringify
};
